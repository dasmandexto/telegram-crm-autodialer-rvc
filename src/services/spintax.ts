/**
 * Spintax parsing and text randomization engine
 * Supports standard {option1|option2|option3} syntax as well as nested spintax.
 */

export class SpintaxService {
  /**
   * Evaluates spintax and returns a randomized variation.
   * Handles nested blocks like "{Здравствуйте|{Добрый день|Приветствую}}".
   */
  static spin(text: string): string {
    if (!text || typeof text !== 'string') return '';

    // RegEx matching innermost {option1|option2|...} without nested curly braces
    const regex = /\{([^{}]+)\}/;

    let result = text;
    let match: RegExpExecArray | null;

    // Safety counter to prevent infinite loops on malformed inputs
    let iterations = 0;
    const maxIterations = 100;

    while ((match = regex.exec(result)) !== null && iterations < maxIterations) {
      iterations++;
      const fullMatch = match[0];
      const choices = match[1].split('|');
      const randomChoice = choices[Math.floor(Math.random() * choices.length)];
      result = result.replace(fullMatch, randomChoice);
    }

    return result;
  }

  /**
   * Checks if string has spintax patterns
   */
  static hasSpintax(text: string): boolean {
    if (!text) return false;
    return /\{[^{}]+\|[^{}]+\}/.test(text);
  }

  /**
   * Computes approximate number of combinations generated by spintax
   */
  static countCombinations(text: string): number {
    if (!text) return 1;
    const regex = /\{([^{}]+)\}/g;
    let count = 1;
    let match: RegExpExecArray | null;

    while ((match = regex.exec(text)) !== null) {
      const choices = match[1].split('|').length;
      if (choices > 0) {
        count *= choices;
      }
    }

    return Math.min(count, 100000);
  }

  /**
   * Counts number of spintax blocks
   */
  static countBlocks(text: string): number {
    if (!text) return 0;
    const matches = text.match(/\{([^{}]+)\}/g);
    return matches ? matches.length : 0;
  }
}
